const getStatus = (total, min) => {
  if (total <= 0) return 'habis';
  if (total < min) return 'menipis';
  return 'normal';
};

const allUkuran = ['XS', 'S', 'M', 'L', 'XL', 'XXL'];

export const warehouseProducts = productTemplates.map((p, idx) => {
  const stockBase = 80 + (idx * 7);
  const minStock = 10 + (idx % 5) * 3;
  const varian = allUkuran.slice(0, 3 + (idx % 4)).map((ukuran, vi) => {
    const stok = Math.floor(stockBase / (3 + (idx % 4))) + (vi * 2) - (idx % 3);
    return {
      ukuran,
      warna: p.warna_hex,
      stok: Math.max(0, stok),
      sku: `${p.kode_produk}-${ukuran}`,
    };
  });
  const total_stok = varian.reduce((a, v) => a + v.stok, 0);
  return {
    ...p,
    varian,
    total_stok,
    stok_minimum: minStock,
    status: getStatus(total_stok, minStock),
  };
});

